package pl.kurs.shop.search;

import com.querydsl.core.types.OrderSpecifier;
import com.querydsl.core.types.dsl.BooleanExpression;
import com.querydsl.core.types.dsl.ComparableExpressionBase;
import com.querydsl.core.types.dsl.Expressions;
import com.querydsl.jpa.JPAExpressions;
import com.querydsl.jpa.impl.JPAQueryFactory;
import org.springframework.data.domain.Pageable;
import org.springframework.data.domain.Sort;
import org.springframework.stereotype.Repository;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.util.StringUtils;
import pl.kurs.shop.model.Product;
import pl.kurs.shop.model.QCategory;
import pl.kurs.shop.model.QReview;
import pl.kurs.shop.model.QManufacturer;
import pl.kurs.shop.model.QProduct;

import java.util.ArrayList;
import java.util.List;

/** Product search on QueryDSL (the classes QProduct, QCategory, ... are generated by querydsl-apt). */
@Repository
@Transactional(readOnly = true)
public class QuerydslSearch {

    private static final QProduct product = QProduct.product;
    private static final QCategory category = QCategory.category;
    private static final QManufacturer manufacturer = QManufacturer.manufacturer;
    private static final QReview review = QReview.review;

    private final JPAQueryFactory queryFactory;

    public QuerydslSearch(JPAQueryFactory queryFactory) {
        this.queryFactory = queryFactory;
    }

    public ResultPage<ProductDto> search(SearchCriteria k, Pageable pageable) {
        BooleanExpression conditions = conditions(k);

        // 1. The page of results. Category and manufacturer are fetched right away (fetchJoin) to avoid N+1.
        List<Product> products = queryFactory
                .selectFrom(product)
                .leftJoin(product.category, category).fetchJoin()
                .leftJoin(product.manufacturer, manufacturer).fetchJoin()
                .where(conditions)
                .orderBy(ordering(pageable.getSort()))
                .offset(pageable.getOffset())
                .limit(pageable.getPageSize())
                .fetch();
        List<ProductDto> results = products.stream().map(ProductDto::from).toList();

        // 2. Total number of results: a separate query with the same conditions.
        Long total = queryFactory
                .select(product.count())
                .from(product)
                .leftJoin(product.category, category)
                .where(conditions)
                .fetchOne();

        return ResultPage.of(results, total == null ? 0 : total, pageable);
    }

    private BooleanExpression conditions(SearchCriteria k) {
        BooleanExpression conditions = Expressions.TRUE.isTrue();
        if (StringUtils.hasText(k.name())) {
            conditions = conditions.and(product.name.lower().like(LikePatterns.contains(k.name()), LikePatterns.ESCAPE));
        }
        if (StringUtils.hasText(k.category())) {
            conditions = conditions.and(category.name.lower().eq(LikePatterns.lowerCase(k.category())));
        }
        if (k.priceFrom() != null) {
            conditions.and(product.price.goe(k.priceFrom()));
        }
        if (k.priceTo() != null) {
            conditions.and(product.price.loe(k.priceTo()));
        }
        if (k.addedFrom() != null) {
            conditions = conditions.and(product.addedAt.goe(k.addedFrom().atStartOfDay()));
        }
        if (k.addedTo() != null) {
            conditions = conditions.and(product.addedAt.lt(k.addedTo().plusDays(1).atStartOfDay()));
        }
        if (k.minRating() != null) {
            conditions = conditions.and(JPAExpressions.selectOne().from(review)
                    .where(review.product.eq(product), review.rating.goe(k.minRating()))
                    .exists());
        }
        if (k.tags() != null) {
            // the product must have EVERY one of the tags; any() is an EXISTS subquery over the collection
            for (String tagName : k.tags()) {
                if (!StringUtils.hasText(tagName)) {
                    continue;
                }
                conditions = conditions.and(product.tags.any().name.lower().eq(LikePatterns.lowerCase(tagName)));
            }
        }
        return conditions;
    }

    private OrderSpecifier<?>[] ordering(Sort sort) {
        List<OrderSpecifier<?>> orders = new ArrayList<>();
        for (Sort.Order o : sort) {
            ComparableExpressionBase<?> field = switch (o.getProperty()) {
                case "name" -> product.name;
                case "price" -> product.price;
                case "addedAt" -> product.addedAt;
                case "category" -> category.name;
                default -> throw new DisallowedSortException(o.getProperty());
            };
            orders.add(o.isAscending() ? field.asc() : field.desc());
        }
        // id last: a stable order of products with the same price/name across pages
        orders.add(product.id.asc());
        return orders.toArray(OrderSpecifier[]::new);
    }
}
